struct id {
    void* data;
    char* name_str;
    Uint32 id : IDENTIFIER_bits;
    Uint32 name_len : IDENTIFIER_NAMELEN_bits;
    enum resource_type : IDENTIFIER_RESOURCETYPE_bits;
};

struct namespace {
    char* name_str;
    struct id* ids[LEINAD_RESOURCETYPE_amount];
    Uint32 id_array_size[LEINAD_RESOURCETYPE_amount];
    Uint32 internal_id : NAMESPACE_bits;
    Uint32 name_len : NAMESPACE_NAMELEN_bits;
};


typedef struct namespaced_id {
    Uint32 namespace;
    Uint32 id;
} namespaced_id_t;


// # DATA

extern struct namespace_data {
    struct namespace* namespaces;
    Uint32 namespace_array_size;

    struct id* (*get_id)(struct namespace* namespace, enum resource_type type, char* name, size_t len);
    struct namespace* (*get_namespace)(char* name, size_t len);
    int (*load_all)(void);
} NAMESPACE;
